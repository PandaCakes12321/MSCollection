package com.teff.puzzles.sweekend;

import android.os.Bundle;

import com.teff.puzzles.common.BaseGameActivity;

/** Spring Weekend: turn rings of figures in the pond until it matches the model. */
public class SweekendActivity extends BaseGameActivity {
    private GameView view;

    @Override
    protected void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        view = new GameView(this);
        setContentView(view);
    }

    GameView gameView() {
        return view;
    }

    @Override
    protected void onResume() {
        super.onResume();
        view.onHostResume();
    }

    @Override
    protected void onPause() {
        view.onHostPause();
        super.onPause();
    }

    @Override
    protected void onDestroy() {
        view.release();
        super.onDestroy();
    }
}
